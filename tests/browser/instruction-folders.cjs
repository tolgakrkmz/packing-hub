const assert = require('node:assert/strict');
const {installStorage} = require('./storage.cjs');
const {assertResponsive} = require('./responsive.cjs');

async function exerciseInstructionFolders({admin, hub, base, device, expect}) {
  console.log('RUN flexible instruction folders → shared database → observer reads nested attachments');
  await admin.context().addInitScript(installStorage, {});
  await admin.goto(base + '/package-instructions');
  await expect(admin.locator('#connDot')).toHaveClass(/\bon\b/);
  await admin.evaluate(async () => {
    await window.__browserTest.ready;
    await window.__browserTest.write('external/Demo customer A/001234/instruction.txt', 'Fictional customer A instruction');
    await window.__browserTest.write('external/Demo customer A/001234/Steps/demo.pdf', '%PDF-1.4\nFictional PDF attachment');
    await window.__browserTest.write('external/Demo customer A/001234/Steps/demo.svg', '<svg xmlns="http://www.w3.org/2000/svg" width="30" height="30"><rect width="30" height="30" fill="blue"/></svg>');
    await window.__browserTest.write('external/Demo customer B/001234/instruction.txt', 'Fictional customer B instruction');
    window.__browserTest.nextDirectory = 'external';
  });
  await admin.locator('#bulkBtn').click();
  await admin.locator('#importLayout').selectOption('clients');
  await admin.locator('#scanExternalBtn').click();
  await expect(admin.locator('#bulkResults .bulk-check')).toHaveCount(2);
  await expect(admin.locator('#bulkResults .bulk-number').first()).toHaveValue('001234');
  await admin.locator('[data-hub-language=en]').click();
  await expect(admin.locator('#importLayout option:checked')).toHaveText('Folder containing customers');
  await expect(admin.locator('#importLayout')).toHaveValue('clients');
  await expect(admin.locator('#bulkResults .bulk-client').first()).toHaveValue('Demo customer A');
  await admin.setViewportSize({width: 390, height: 844});
  await assertResponsive(admin, 'Fictional folder import on mobile');
  await admin.setViewportSize({width: 1280, height: 800});
  await admin.locator('[data-hub-language=bg]').click();
  await admin.locator('#bulkImportBtn').click();
  await expect.poll(() => Object.values(hub.store.get('package-instructions').data).filter(row => row.number === '001234').length).toBe(2);
  await expect(admin.locator('#bulkPanel')).toBeHidden();
  const records = Object.values(hub.store.get('package-instructions').data);
  assert.deepEqual(records.find(row => row.client === 'Demo customer A').images, ['Steps/demo.pdf', 'Steps/demo.svg']);
  assert.equal(Buffer.from(hub.store.node('data/profiles/Demo customer A/001234/Steps/demo.pdf').content).toString(), '%PDF-1.4\nFictional PDF attachment');
  await admin.locator('#searchInput').fill('001234');
  const customerB = admin.locator('.result-card').filter({hasText: 'Demo customer B'});
  await customerB.locator('.result-head').click();
  await customerB.locator('.cat-select').selectOption('special');
  await expect.poll(() => Object.values(hub.store.get('package-instructions').data).find(row => row.client === 'Demo customer B').category).toBe('special');
  assert.equal(Object.values(hub.store.get('package-instructions').data).find(row => row.client === 'Demo customer A').category, null);
  await admin.locator('#bulkBtn').click();
  await admin.locator('#scanExternalBtn').click();
  await expect(admin.locator('#bulkResults .bulk-check')).toHaveCount(2);
  await expect(admin.locator('#bulkResults .bulk-check:checked')).toHaveCount(0);
  await expect(admin.locator('#bulkSelectAll')).not.toBeChecked();
  await admin.locator('#bulkSelectAll').check();
  await expect(admin.locator('#bulkResults .bulk-check:checked')).toHaveCount(2);
  await admin.locator('#bulkImportBtn').click();
  await expect(admin.locator('#bulkStatus')).toHaveText('Готово — импортирани 0 от 2.');
  assert.equal(Object.keys(hub.store.get('package-instructions').data).length, 2);
  await admin.locator('#bulkCancelBtn').click();

  await admin.locator('#bulkBtn').click();
  await admin.locator('#importLayout').selectOption('profile');
  await admin.evaluate(() => { window.__browserTest.nextDirectory = 'external/Demo customer B/001234'; });
  await admin.locator('#scanExternalBtn').click();
  await expect(admin.locator('#bulkResults .bulk-check')).toHaveCount(1);
  await admin.locator('#bulkResults .bulk-client').fill('Demo customer C');
  await admin.locator('#bulkImportBtn').click();
  await expect.poll(() => Object.values(hub.store.get('package-instructions').data).filter(row => row.number === '001234').length).toBe(3);
  assert.ok(Object.values(hub.store.get('package-instructions').data).some(row => row.folderName === 'Demo customer C/001234'));
  await expect(admin.locator('#bulkPanel')).toBeHidden();

  await hub.auth.create('demo-instruction-observer', 'Fictional-password-123', 'observer', hub.auth.list()[0]);
  const observer = await device('demo-instruction-observer', true);
  await observer.goto(base + '/package-instructions');
  await expect(observer.locator('#connDot')).toHaveClass(/\bon\b/);
  await expect(observer.locator('#addBtn')).toBeHidden();
  await expect(observer.locator('#bulkBtn')).toBeHidden();
  await observer.locator('#searchInput').fill('demo.pdf');
  await expect(observer.locator('.result-card')).toHaveCount(1);
  await observer.locator('.result-head').click();
  await expect(observer.locator('.result-text')).toHaveText('Fictional customer A instruction');
  await expect(observer.locator('.cat-select')).toBeHidden();
  await observer.locator('.gallery img').click();
  await expect(observer.locator('#lightbox')).toHaveClass(/open/);
  assert.equal(await observer.locator('#lightboxImg').evaluate(image => image.complete && image.naturalWidth === 30), true);
  await observer.locator('#lightboxClose').click();
  const download = observer.waitForEvent('download');
  await observer.locator('.file-tile').click();
  assert.equal((await download).suggestedFilename(), 'demo.pdf');
  await assertResponsive(observer, 'Fictional instruction attachments on mobile');
  await observer.context().close();
  console.log('PASS flexible folder import, shared storage, duplicate numbers, repeated import, categories, nested attachments and mobile read access');
}
module.exports = {exerciseInstructionFolders};
