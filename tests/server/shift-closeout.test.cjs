const test = require('node:test');
const assert = require('node:assert/strict');
const {openStore, shiftSchedule:schedule} = require('../../server/store.cjs');
const {summarizeShift, createShiftCloseout} = require('../../server/shift-closeout.cjs');
const {permissionsFor} = require('../../server/permissions.cjs');
const date='2026-10-05';
const scope=(day=date,code=1)=>({date:day,team:schedule.teamFor(schedule.parseDate(day),code),shiftCode:code});
const sources=(extra={})=>({productionEntries:[],pairEntries:[],now:Date.parse(date+'T12:00:00+03:00'),...extra});
const chief=team=>({role:'operator',taskSupervisor:true,taskTeam:team});
test('mandatory production counts committed zero entries independently of pairs and other scopes',()=>{
  const s=scope(), report={id:'demo-zero',date,shift:s.team,tonnage:0,brak:0};
  assert.equal(summarizeShift(s,sources()).production.state,'missing');
  assert.equal(summarizeShift(s,sources({productionEntries:[report, {...report,id:'demo-two'}]})).production.entryCount,2);
  assert.equal(summarizeShift(s,sources({productionEntries:[report]})).production.state,'entered');
  assert.equal(summarizeShift(s,sources({productionEntries:[{...report,date:'2026-10-04'}]})).production.state,'missing');
  const pair=(id,extra={})=>({...s,id,members:[{id:'demo-one',name:'Demo One'},{id:'demo-two',name:'Demo Two'}],...extra});
  const result=summarizeShift(s,sources({pairEntries:[pair('demo-pending'),pair('demo-result',{result:{kg:0,crates:0}}),pair('demo-cancel',{cancellation:{reasonKey:'cleaning',reasonText:''}}),pair('demo-wrong',{shiftCode:2})]}));
  assert.deepEqual([result.pairs.planned,result.pairs.reported,result.pairs.pending,result.pairs.cancelled],[3,1,1,1]);
  assert.equal(result.pairs.entries[2].reasonKey,'cleaning'); assert.equal(result.production.state,'missing');
});
test('rest, upcoming, ended and overdue use Sofia intervals including DST and Stickers',()=>{
  const s=scope('2026-10-24',3), interval=schedule.shiftInterval(s.team,s.date);
  assert.equal(interval.end-interval.start,9*3600000);
  assert.equal(summarizeShift(s,sources({now:interval.start-1})).phase,'upcoming');
  assert.equal(summarizeShift(s,sources({now:interval.end})).phase,'ended');
  assert.equal(summarizeShift(s,sources({now:interval.end+600000})).phase,'overdue');
  const stickers={date:'2026-10-05',team:'СТИКЕРИ',shiftCode:1};
  assert.equal(new Date(summarizeShift(stickers,sources()).interval.end).toISOString(),'2026-10-05T14:30:00.000Z');
  const rest=summarizeShift({...stickers,date:'2026-10-04'},sources());
  assert.equal(rest.phase,'rest'); assert.equal(rest.production.state,'not-applicable');
});
test('service defaults, scope validation, permissions and partial visibility never leak hidden reports',t=>{
  const store=openStore(':memory:');t.after(()=>store.close());
  const s=scope(), service=createShiftCloseout(store,{now:()=>Date.parse(date+'T12:00:00+03:00')}), user=chief(s.team);
  assert.equal(permissionsFor(user).canViewShiftCloseout,true);
  assert.equal(permissionsFor({role:'observer'}).canViewShiftCloseout,false);
  assert.equal(service.read(s,user).production.state,'missing');
  assert.deepEqual(service.read({},user).teams,[s.team]);
  assert.equal(service.read({},chief('')).configurationRequired,true);
  for(const input of [{...s,date:'2026-02-30'},{...s,team:'other'},{...s,shiftCode:2},{...s,shiftCode:'01'},new URLSearchParams('date=2026-10-05&date=2026-10-06')])assert.throws(()=>service.read(input,{role:'admin'}),{status:400});
  assert.throws(()=>service.read(s,{role:'observer'}),{status:403});
  assert.throws(()=>service.read({...s,team:schedule.teamFor(schedule.parseDate(date),2)},user),{status:403});
  assert.throws(()=>service.read(s,{...user,permissionOverrides:{canViewShiftCloseout:false}}),{status:403});
  const limited=service.read(s,{...user,permissionOverrides:{canViewProduction:false}});
  assert.equal(limited.production,null);assert.equal(limited.availability.production,false);
  const night=scope(date,3), early=createShiftCloseout(store,{now:()=>schedule.shiftInterval(night.team,date).end-3600000});
  assert.equal(early.read({}, {role:'admin'}).scope.date,date);
  assert.equal(early.read({}, {role:'admin'}).scope.shiftCode,3);
});
test('API requires login, GET, current account rights and rejects malformed scopes',async t=>{
  const {createHubServer}=require('../../server/server.cjs');
  const hub=createHubServer({filename:':memory:',publicOrigin:'http://127.0.0.1:0',allowHttp:true});
  await new Promise(resolve=>hub.server.listen(0,'127.0.0.1',resolve));t.after(()=>hub.close());
  const admin=await hub.auth.create('demo-closeout-admin','Fictional-password-123','admin');
  const login=await hub.auth.login(admin.username,'Fictional-password-123');
  const base='http://127.0.0.1:'+hub.server.address().port;
  const headers={Origin:base,Cookie:'hub-local-session='+login.token,'X-CSRF-Token':login.csrf};
  assert.equal((await fetch(base+'/api/shift-closeout')).status,401);
  assert.equal((await fetch(base+'/api/shift-closeout',{headers})).status,200);
  assert.equal((await fetch(base+'/api/shift-closeout',{headers,method:'POST'})).status,405);
  assert.equal((await fetch(base+'/api/shift-closeout?date=bad',{headers})).status,400);
  await hub.auth.update(admin.id,{permissions:{canViewShiftCloseout:false}},admin);
  const next=await hub.auth.login(admin.username,'Fictional-password-123');
  assert.equal((await fetch(base+'/api/shift-closeout',{headers:{Cookie:'hub-local-session='+next.token}})).status,403);
});
